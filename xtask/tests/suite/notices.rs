#[test]
fn a_library_under_a_licence_that_asks_for_its_source_says_where_its_source_is() {
    assert!(notices::asks_for_source("MPL-2.0") && notices::asks_for_source("LGPL-2.1-or-later"));
    for asks_only_a_notice in ["MIT", "Apache-2.0", "BSD-3-Clause", "ISC", "Unicode-3.0", "Zlib", "CC0-1.0"] {
        assert!(!notices::asks_for_source(asks_only_a_notice), "{asks_only_a_notice}");
    }
    let text = "Mozilla Public License Version 2.0, which goes on for a long while. ".repeat(4);
    let group = |name: &str| Group {
        licence: "MPL-2.0".to_string(),
        called: "Mozilla Public License 2.0".to_string(),
        libraries: vec![Library {
            name: name.to_string(),
            version: "0.2.0".to_string(),
            ..Library::default()
        }],
        text: text.clone(),
        ..Group::default()
    };
    // As it is laid out, each kind of library says where its own is kept.
    let file = notices::whole(
        &marks(),
        &format!("\n{}", notices::half(&[group("a-crate")], Of::Crates)),
        &format!("\n{}", notices::half(&[group("a-package")], Of::Packages)),
    );
    for wanted in [
        "- `a-crate` 0.2.0\n  Source: this is `a-crate` 0.2.0 as its authors published it, with nothing in it changed here. Its source is that crate: https://crates.io/crates/a-crate/0.2.0\n",
        "Its source is that package: https://www.npmjs.com/package/a-package/v/0.2.0\n",
    ] {
        assert!(file.contains(wanted), "`{wanted}` in\n{file}");
    }
    assert_eq!(notices::amiss(&notices::read(&file), &[]), Vec::<String>::new());
    // One that came in with no such line is refused, so that a second
    // library under such a licence cannot be handed on saying nothing.
    let silent: String =
        file.lines().filter(|line| !line.contains(notices::SOURCE)).map(|line| format!("{line}\n")).collect();
    let problems = notices::amiss(&notices::read(&silent), &[]);
    assert_eq!(problems.len(), 2, "{problems:?}");
    assert!(
        problems[0].contains("the crate `a-crate` 0.2.0 is under `MPL-2.0`, which asks that whoever hands on a copy says where its source is, and no line under it says so"),
        "{problems:?}"
    );
    // The one there is today has its line.
    let today = the_file();
    let under: Vec<&notices::Named> =
        today.crates.iter().filter(|one| notices::asks_for_source(&one.licence)).collect();
    assert!(
        under.iter().all(|one| one.said.iter().any(|said| said.starts_with(notices::SOURCE))),
        "{under:?}"
    );
}

