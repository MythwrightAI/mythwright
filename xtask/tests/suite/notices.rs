#[test]
fn records_that_are_not_whole_are_refused_saying_what_is_missing() {
    for (written, why) in [
        ("%%licence%% MIT\n%%library%% one 1.0.0\n%%text%%\nnever ended\n", "the last text has no end"),
        ("%%licence%% MIT\n%%library%% one\n", "says no version"),
        ("%%licence%% MIT\n%%text%%\nwords\n%%end%%\n", "has no library or no text"),
        ("%%licence%% MIT\n%%library%% one 1.0.0\n%%text%%\n%%end%%\n", "has no library or no text"),
        ("%%library%% one 1.0.0\n", "before any licence"),
        ("%%licence%% MIT\n%%colour%% blue\n", "is no field of a record"),
        ("%%licence%%\n%%library%% one 1.0.0\n%%text%%\nwords\n%%end%%\n", "names no licence"),
    ] {
        let refused = notices::records(written).unwrap_err();
        assert!(refused.contains(why), "`{why}` in `{refused}`");
    }
    assert_eq!(notices::records("").unwrap(), Vec::<Group>::new());
}
