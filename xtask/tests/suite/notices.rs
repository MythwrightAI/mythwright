fn manifests() -> Vec<(String, String)> {
    let cli = "[package]\nname = \"cli\"\n\n[dependencies]\nbuilt = { workspace = true }\nkernel = { workspace = true }\nshort.workspace = true\n\n[build-dependencies]\nruns-in-a-build = { workspace = true }\n\n[dev-dependencies]\nonly-tested = { workspace = true }\n";
    let desktop = "[package]\nname = \"desktop\"\n\n[dependencies]\nkernel = { workspace = true }\n\n[target.'cfg(windows)'.dependencies]\none-systems = { workspace = true }\n";
    let kernel = "[package]\nname = \"kernel\"\n\n[dependencies]\ntwice = { workspace = true }\n";
    let tooling = "[package]\nname = \"tooling\"\n\n[dependencies]\nnobody-ships = { workspace = true }\n";
    [("cli", cli), ("desktop", desktop), ("kernel", kernel), ("tooling", tooling)]
        .map(|(name, manifest)| (name.to_string(), manifest.to_string()))
        .to_vec()
}

fn names(reached: &[shipped::Locked]) -> Vec<String> {
    reached.iter().map(|one| format!("{} {}", one.name, one.version)).collect()
}

#[test]
fn the_crates_the_programs_can_be_built_from_are_read_from_the_lock_and_the_manifests() {
    let reached = shipped::reached(LOCK, ROOT, &manifests(), &["cli", "desktop"]);
    // Somebody else's crates only: what a program asks for, what that is
    // built from, what a build runs, what one kind of system has, both
    // versions of a crate there are two of, and a crate asked for under
    // another name than its own. Not what only a test uses or what that
    // is built from, and not what something that is no program uses.
    assert_eq!(
        names(&reached),
        [
            "built 1.0.0",
            "its-real-name 0.3.0",
            "one-systems 0.2.0",
            "runs-in-a-build 0.9.0",
            "twice 1.0.0",
            "twice 2.0.0"
        ]
    );
    assert_eq!(
        shipped::asked(&manifests()[0].1).into_iter().collect::<Vec<_>>(),
        ["built", "kernel", "runs-in-a-build", "short"]
    );
    assert_eq!(shipped::renamed(ROOT).get("short").map(String::as_str), Some("its-real-name"));
}

#[test]
fn the_mark_of_those_crates_moves_when_one_of_them_does_and_for_nothing_else() {
    let mark = |lock: &str, manifests: &[(String, String)]| {
        shipped::mark(&shipped::reached(lock, ROOT, manifests, &["cli", "desktop"]))
    };
    let was = mark(LOCK, &manifests());
    // The product's own version being another, a crate only the tests use
    // being another, and a crate of something that is no program: none is
    // in a package, and the notices are not to be made again for one.
    let bumped = LOCK.replace("version = \"0.1.0\"", "version = \"0.2.0\"");
    assert_ne!(bumped, LOCK);
    assert_eq!(mark(&bumped, &manifests()), was);
    let tests_moved = LOCK.replace("version = \"5.0.0\"", "version = \"5.1.0\"").replace("ffff", "abab");
    assert_eq!(mark(&tests_moved, &manifests()), was);
    assert_eq!(mark(&LOCK.replace("9999", "8888"), &manifests()), was);
    // Another version of a crate a program is built from, and other bytes
    // under the same version, are another thing handed on.
    assert_ne!(mark(&LOCK.replace("version = \"0.9.0\"", "version = \"0.9.1\""), &manifests()), was);
    assert_ne!(mark(&LOCK.replace("bbbb", "bbbc"), &manifests()), was);
    // And so is a crate that only a test used coming to be built into a
    // program, which changes no line of the lock.
    let mut moved = manifests();
    moved[0].1 = moved[0].1.replace("[dev-dependencies]\n", "");
    let now = shipped::reached(LOCK, ROOT, &moved, &["cli", "desktop"]);
    assert!(names(&now).contains(&"only-tested 5.0.0".to_string()), "{:?}", names(&now));
    assert!(names(&now).contains(&"test-helper 1.1.0".to_string()), "{:?}", names(&now));
    assert_ne!(shipped::mark(&now), was);
}

