//! The notices of other people's libraries that a package carries: that
//! the file at the top of the repository was made from what is bundled
//! now, and that what it names is whole, both asked with no tool; and the
//! parts those are asked of, each as a function of texts.
//!
//! The command that makes the file is run in `noticed.rs`.

use std::path::Path;

use xtask::notices::{self, Group, Library, Of};
use xtask::shipped;

/// The top of the repository this is a test of.
fn top() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap()
}

fn the_file() -> notices::Read {
    let file = std::fs::read_to_string(top().join(notices::FILE))
        .unwrap_or_else(|err| panic!("{} at the top of the repository: {err}", notices::FILE));
    notices::read(&file)
}

#[test]
fn the_notices_a_package_carries_were_made_from_what_is_bundled_now() {
    let notices::Now { marks, reached, .. } = notices::now(top()).unwrap();
    let read = the_file();
    // The crates the programs can be built from, what the tool goes by
    // and what it writes by are what the file says it was made from.
    let mut problems = notices::stale(&read, &marks);
    // And each library it names is the one that is locked: a crate among
    // what the programs are built from, a package in the client's lock.
    problems.extend(notices::not_locked(&read, &reached));
    let lock = std::fs::read_to_string(top().join("ui/package-lock.json")).unwrap();
    problems.extend(notices::not_installed(&read, &lock));
    assert!(
        problems.is_empty(),
        "a dependency was added, updated or taken away, and the notices were not made again:\n{}\n\n`{}` \
         makes them (it needs `cargo-about`: `{}`); commit what it writes",
        problems.join("\n"),
        notices::COMMAND,
        notices::INSTALL
    );
}

#[test]
fn every_library_in_the_notices_names_a_licence_and_has_its_text_and_none_is_the_products_own() {
    let own = notices::now(top()).unwrap().own;
    let read = the_file();
    let problems = notices::amiss(&read, &own);
    assert!(problems.is_empty(), "{}", problems.join("\n"));
    // Both halves are there, and the programs' is of every system: a crate
    // that only Windows builds and one that only macOS builds are named.
    assert!(notices::libraries(&read.crates) > 100 && notices::libraries(&read.packages) > 10);
    for one_systems in ["windows-sys", "objc2", "inotify"] {
        assert!(read.crates.iter().any(|one| one.name == one_systems), "{one_systems} is in a package");
    }
    assert!(own.iter().any(|name| name == "cli") && own.iter().any(|name| name == "xtask"), "{own:?}");
    // What was read is the whole of each half: written again from it, the
    // file is the file.
    let file = std::fs::read_to_string(top().join(notices::FILE)).unwrap();
    assert_eq!(notices::whole(&read.marks, &read.crates_half, &read.packages_half), file);
    // And nothing in it says where it was made.
    for line in file.lines() {
        assert!(!line.contains("/home/") && !line.contains("/Users/") && !line.contains(":\\"), "{line}");
    }
}

